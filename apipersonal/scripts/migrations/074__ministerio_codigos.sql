-- 074__ministerio_codigos.sql
-- Catalogo de las novedades del combo de la Intranet MS (Parte de Novedades ->
-- personalnovedad). Antes la lista salia solo de mapeo_novedades + el Excel del
-- Ministerio, asi que los codigos sin uso (NP1, 28, 34, ...) no se podian mapear.
--
-- novedad = formato del mapeo ('01-POR RAZONES DE ENFERMEDAD'); el combo muestra
--   '01 - POR RAZONES DE ENFERMEDAD' (mapeo_novedades._label hace la conversion).
-- vigente = 1 si aparecio en la ultima lectura del combo. Lo mantiene el robot
--   intranet_control_codigos (alta de nuevos, baja de los que desaparecen).
-- Carga inicial: las 70 opciones del combo al 13/10/2026 (capturas del usuario).

CREATE TABLE IF NOT EXISTS ministerio_codigos (
  codigo VARCHAR(10) NOT NULL,
  novedad VARCHAR(150) NOT NULL,
  vigente TINYINT(1) NOT NULL DEFAULT 1,
  visto_primero DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  visto_ultimo DATETIME NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (codigo),
  UNIQUE KEY uq_ministerio_codigos_novedad (novedad)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

