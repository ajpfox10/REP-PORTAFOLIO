-- Correcciones de mapeo detectadas al cruzar con el combo (13/10/2026):
-- NACIMIENTO PREMATURO ALTO RIESGO se cargaba como 06-MATERNIDAD -> NP1.
UPDATE mapeo_novedades SET usar_para_cargar = 0, activo = 0,
       observacion = '074: reemplazada por NP1-NACIMIENTO PREMATURO'
 WHERE novedad_siape = 'NACIMIENTO PREMATURO ALTO RIESGO' AND codigo_cie = ''
   AND novedad_ministerio = '06-POR MATERNIDAD';
-- COMISION figuraba como equivalente de 22-ACTIVIDAD GREMIAL -> 30.
UPDATE mapeo_novedades SET usar_para_cargar = 0, activo = 0,
       observacion = '074: reemplazada por 30-COMISION DE SERVICIOS'
 WHERE novedad_siape = 'COMISION' AND codigo_cie = '' AND novedad_ministerio = '22-ACTIVIDAD GREMIAL';

-- Novedades SIAPE sin mapeo (historial desde 2024) -> codigo del combo.
-- Quedan afuera a proposito, hasta que el usuario decida: francos (34), LLEGO TARDE,
-- PATOLOGIAS CRONICAS, FESTIVIDAD JUDIA, sin haberes, examen aptitud fisica, GREMIAL.
-- usar_para_cargar = 1 salvo que la novedad SIAPE ya tenga otra regla de carga
-- general activa (uq_carga) -> en ese caso entra solo como equivalencia.
-- observacion 'inicial:' para que "Restaurar default" las conserve; las dos reemplazadas
-- de arriba dejan de ser 'inicial:' y el restaurar no las prende.
INSERT IGNORE INTO mapeo_novedades (novedad_siape, codigo_cie, novedad_ministerio, usar_para_cargar, observacion)
SELECT n.siape, '', n.min,
       IF(EXISTS (SELECT 1 FROM mapeo_novedades x
                   WHERE x.novedad_siape = n.siape AND x.codigo_cie = ''
                     AND x.usar_para_cargar = 1 AND x.activo = 1), 0, 1),
       'inicial: 074 combo Intranet completo'
FROM (
            SELECT 'NACIMIENTO PREMATURO ALTO RIESGO' siape, 'NP1-NACIMIENTO PREMATURO' min
  UNION ALL SELECT 'NACIMIENTO PREMATURO BAJO RIESGO', 'NP1-NACIMIENTO PREMATURO'
  UNION ALL SELECT 'NACIMIENTO PRE-TERMINO', 'NP1-NACIMIENTO PREMATURO'
  UNION ALL SELECT 'COMISION', '30-COMISION DE SERVICIOS'
  UNION ALL SELECT 'COMISION DE ENTRADA', '30-COMISION DE SERVICIOS'
  UNION ALL SELECT 'AUSENTE SIN AVISO', '28-INASISTENCIA'
  UNION ALL SELECT 'BOLETA DE SALIDA', '43-PERMISO HORAS DE SALIDA'
  UNION ALL SELECT 'BOLETA DE SALIDA - OFICIAL', '43-PERMISO HORAS DE SALIDA'
  UNION ALL SELECT 'ASUETO', 'AS-ASUETO'
  UNION ALL SELECT 'PARO TRANSPORTE', 'PAT-PARO DE TRANSPORTE'
  UNION ALL SELECT 'PARO', 'PA-PARO'
  UNION ALL SELECT 'BOLETA DE SALIDA-OFICIAL', '43-PERMISO HORAS DE SALIDA'
  UNION ALL SELECT 'PRACT. OBLIG. DE GRADO O POST GRADO UNIV.-TERC.', '45-POR PRACTICAS OBLIGAORIAS'
  UNION ALL SELECT 'PRACT.OBLIG.DE GRADO O POST GRADO UNIV.-TERC.', '45-POR PRACTICAS OBLIGAORIAS'
  UNION ALL SELECT 'DUELO DIRECTO a mas de 200 Km', '14-DUELO FAMILIAR DIRECTO'
  UNION ALL SELECT 'DUELO INDIRECTO a mas de 200 Km', '15-DUELO FAMILIAR INDIRECTO'
  UNION ALL SELECT 'DONACION DE SANGRE', '33-POR DONACIÓN DE SANGRE'
  UNION ALL SELECT 'PRE-JUBILATORIO', '94-PRE-JUBILATORIO (Reducción horaria)'
  UNION ALL SELECT 'ULTIMA MATERIA', '19-POR ÚLTIMA MATERIA'
  UNION ALL SELECT 'NACIMIENTO CORRESPONSABLE PARENTAL NO GESTANTE', '311-LICENCIA POR NACIMIENTO CORRESPONSAL PARENTAL NO GESTANTE'
  UNION ALL SELECT 'PARA MUJERES VICTIMAS DE VIOLENCIA. PRORROGA', 'VV-MUJER VICTIMA DE VIOLENCIA DE GENERO'
  UNION ALL SELECT 'TRATAMIENTO DE FERTILIDAD ASISTIDA', '6F1-FERTILIZACION ASISTIDA C SUELDO'
  UNION ALL SELECT 'JUNTA MEDICA', 'JM-JUNTA MÉDICA'
  UNION ALL SELECT 'PERDIDA DE GESTACION', '111-POR DEFUNCIÓN FETAL'
  UNION ALL SELECT 'NACIMIENTO SIN VIDA O FALLECIMIENTO', '111-POR DEFUNCIÓN FETAL'
  UNION ALL SELECT 'ADOPCION', '421-POR ADOPCION'
  UNION ALL SELECT 'CUIDADO RECIEN NACIDO/A INTERNADO', 'RN1-RECIEN NACIDO'
  UNION ALL SELECT 'FALLECIMIENTO CORRESPONSABLE PARENTAL', '141-FALLECIMIENTO DE CORRESPONSAL PARENTAL CON HIJO MENOR 18 Y/O DISC'
) n;
