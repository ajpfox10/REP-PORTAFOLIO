-- 089__licencias_plus_norma.sql
-- Cómo cuenta cada licencia del Ministerio para el plus de Guardia y de Planta (Ley 10471).
-- Tabla aparte de ministerio_codigos para no interferir con el robot que la sincroniza
-- (intranet_control_codigos) y poder incluir 29/93, que no están en el combo.
--
-- Valores:
--   EXCEPTUADA = la norma dice que NO es inasistencia (no descuenta).
--   ENFERMEDAD = no descuenta hasta el tope y después aplica la escala
--                (guardia: 1 guardia ok, 2→75%, 3→50%, 4→25%; planta: 6 días ok, 12→75%, 18→50%, 24→25%).
--   NEUTRA     = no es una ausencia (franco, comisión, horas de salida, asueto).
--   DESCUENTA  = la norma no la nombra → es causal de descuento (criterio del usuario, 20/10/2026).
-- Normas: guardia Dto 14/2026 art. 4 (desde 01/05/2025); planta Dto 375/08 art. 1 + Acta 28/03/2022 (Dto 1434/23).
-- Idempotente: no pisa lo que el usuario ya editó.

CREATE TABLE IF NOT EXISTS licencias_plus_norma (
  codigo VARCHAR(10) NOT NULL,
  novedad VARCHAR(150) NOT NULL,
  guardia ENUM('EXCEPTUADA','ENFERMEDAD','NEUTRA','DESCUENTA') NOT NULL DEFAULT 'DESCUENTA',
  planta  ENUM('EXCEPTUADA','ENFERMEDAD','NEUTRA','DESCUENTA') NOT NULL DEFAULT 'DESCUENTA',
  norma_guardia VARCHAR(120) NULL,
  norma_planta  VARCHAR(120) NULL,
  observacion VARCHAR(255) NULL,
  updated_by INT NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (codigo)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

